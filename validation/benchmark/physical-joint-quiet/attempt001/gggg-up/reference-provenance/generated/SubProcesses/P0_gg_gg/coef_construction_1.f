      SUBROUTINE ML5_0_COEF_CONSTRUCTION_1(P,NHEL,H,IC)
C     
C     Modules
C     
      USE ML5_0_POLYNOMIAL_CONSTANTS
      USE ALOHA_OBJECT
C     
      IMPLICIT NONE
C     
C     CONSTANTS
C     
      INTEGER    NEXTERNAL
      PARAMETER (NEXTERNAL=4)
      INTEGER    NCOMB
      PARAMETER (NCOMB=16)
      INTEGER    NLOOPS, NLOOPGROUPS, NCTAMPS
      PARAMETER (NLOOPS=6, NLOOPGROUPS=6, NCTAMPS=38)
      INTEGER    NLOOPAMPS
      PARAMETER (NLOOPAMPS=44)
      INTEGER    NWAVEFUNCS,NLOOPWAVEFUNCS
      PARAMETER (NWAVEFUNCS=4,NLOOPWAVEFUNCS=18)
      REAL*8     ZERO
      PARAMETER (ZERO=0D0)
      REAL*16     MP__ZERO
      PARAMETER (MP__ZERO=0.0E0_16)
C     These are constants related to the split orders
      INTEGER    NSO, NSQUAREDSO, NAMPSO
      PARAMETER (NSO=1, NSQUAREDSO=1, NAMPSO=1)
C     
C     ARGUMENTS
C     
      REAL*8 P(0:3,NEXTERNAL)
      INTEGER NHEL(NEXTERNAL), IC(NEXTERNAL)
      INTEGER H
C     
C     LOCAL VARIABLES
C     
      INTEGER I,J,K
      INTEGER FLAVOR(NEXTERNAL)
      DATA FLAVOR /NEXTERNAL*1/
      COMPLEX*16 COEFS(MAXLWFSIZE,0:VERTEXMAXCOEFS-1,MAXLWFSIZE)

      LOGICAL DUMMYFALSE
      DATA DUMMYFALSE/.FALSE./
C     
C     GLOBAL VARIABLES
C     

      INCLUDE 'coupl.inc'
      INCLUDE 'mp_coupl.inc'

      INTEGER HELOFFSET
      INTEGER GOODHEL(NCOMB)
      LOGICAL GOODAMP(NSQUAREDSO,NLOOPGROUPS)
      COMMON/ML5_0_FILTERS/GOODAMP,GOODHEL,HELOFFSET

      LOGICAL CHECKPHASE
      LOGICAL HELDOUBLECHECKED
      COMMON/ML5_0_INIT/CHECKPHASE, HELDOUBLECHECKED

      INTEGER SQSO_TARGET
      COMMON/ML5_0_SOCHOICE/SQSO_TARGET

      LOGICAL UVCT_REQ_SO_DONE,MP_UVCT_REQ_SO_DONE,CT_REQ_SO_DONE
     $ ,MP_CT_REQ_SO_DONE,LOOP_REQ_SO_DONE,MP_LOOP_REQ_SO_DONE
     $ ,CTCALL_REQ_SO_DONE,FILTER_SO
      COMMON/ML5_0_SO_REQS/UVCT_REQ_SO_DONE,MP_UVCT_REQ_SO_DONE
     $ ,CT_REQ_SO_DONE,MP_CT_REQ_SO_DONE,LOOP_REQ_SO_DONE
     $ ,MP_LOOP_REQ_SO_DONE,CTCALL_REQ_SO_DONE,FILTER_SO

      INTEGER I_SO
      COMMON/ML5_0_I_SO/I_SO
      INTEGER I_LIB
      COMMON/ML5_0_I_LIB/I_LIB

      TYPE(ALOHA) W(NWAVEFUNCS)
      COMMON/ML5_0_W/W
      COMPLEX*16 WL(MAXLWFSIZE,0:LOOPMAXCOEFS-1,MAXLWFSIZE,
     $ -1:NLOOPWAVEFUNCS)
      COMPLEX*16 PL(0:3,-1:NLOOPWAVEFUNCS)
      COMMON/ML5_0_WL/WL,PL

      COMPLEX*16 AMPL(3,NLOOPAMPS)
      COMMON/ML5_0_AMPL/AMPL

C     
C     ----------
C     BEGIN CODE
C     ----------

C     The target squared split order contribution is already reached
C      if true.
      IF (FILTER_SO.AND.LOOP_REQ_SO_DONE) THEN
        GOTO 1001
      ENDIF

C     IREGI audit: actual HELAS external polarization components.
      WRITE(*,*) 'IREGI_HELICITY',H,NHEL
C     MadLoop may project the requested phase-space point before HELAS.
C     All cases here have two incoming particles. HELAS stores their
C     momenta with the opposite sign, and outgoing momenta with + sign.
      DO I=1,4
        WRITE(*,'(A,I4,4ES26.17E3)') 'IREGI_SEAM_EXTERNAL ',I,
     $    (P(J,I),J=0,3)
        IF(I.LE.2) THEN
          WRITE(*,'(A,I4,4ES26.17E3)') 'IREGI_EVALUATED_EXTERNAL ',I,
     $      (-DBLE(W(I)%P(J)),J=0,3)
        ELSE
          WRITE(*,'(A,I4,4ES26.17E3)') 'IREGI_EVALUATED_EXTERNAL ',I,
     $      (DBLE(W(I)%P(J)),J=0,3)
        ENDIF
        DO J=0,3
          WRITE(*,'(A,2I4,2ES26.17E3)') 'IREGI_WAVEFUNCTION_P ',I,J,
     $      DBLE(W(I)%P(J)),DIMAG(W(I)%P(J))
        ENDDO
      ENDDO
      DO I=1,4
        DO J=1,4
          WRITE(*,'(A,2I4,2ES26.17E3)') 'IREGI_WAVEFUNCTION ',I,J,
     $      DBLE(W(I)%W(J)),DIMAG(W(I)%W(J))
        ENDDO
      ENDDO
C     Coefficient construction for loop diagram with ID 1
      CALL FFV1L1_2(PL(0,0),W(1),GC_5,ZERO,ZERO,PL(0,1),COEFS)
      CALL ML5_0_UPDATE_WL_0_1(WL(1,0,1,0),4,COEFS,4,4,WL(1,0,1,1))
      CALL FFV1L1_2(PL(0,1),W(2),GC_5,ZERO,ZERO,PL(0,2),COEFS)
      CALL ML5_0_UPDATE_WL_1_1(WL(1,0,1,1),4,COEFS,4,4,WL(1,0,1,2))
      CALL FFV1L1_2(PL(0,2),W(4),GC_5,ZERO,ZERO,PL(0,3),COEFS)
      CALL ML5_0_UPDATE_WL_2_1(WL(1,0,1,2),4,COEFS,4,4,WL(1,0,1,3))
      CALL FFV1L1_2(PL(0,3),W(3),GC_5,ZERO,ZERO,PL(0,4),COEFS)
      CALL ML5_0_UPDATE_WL_3_1(WL(1,0,1,3),4,COEFS,4,4,WL(1,0,1,4))
      CALL ML5_0_CREATE_LOOP_COEFS(WL(1,0,1,4),4,4,1,1,1,39)
C     Coefficient construction for loop diagram with ID 2
      CALL FFV1L1_2(PL(0,2),W(3),GC_5,ZERO,ZERO,PL(0,5),COEFS)
      CALL ML5_0_UPDATE_WL_2_1(WL(1,0,1,2),4,COEFS,4,4,WL(1,0,1,5))
      CALL FFV1L1_2(PL(0,5),W(4),GC_5,ZERO,ZERO,PL(0,6),COEFS)
      CALL ML5_0_UPDATE_WL_3_1(WL(1,0,1,5),4,COEFS,4,4,WL(1,0,1,6))
      CALL ML5_0_CREATE_LOOP_COEFS(WL(1,0,1,6),4,4,2,1,1,40)
C     Coefficient construction for loop diagram with ID 3
      CALL FFV1L2_1(PL(0,0),W(1),GC_5,ZERO,ZERO,PL(0,7),COEFS)
      CALL ML5_0_UPDATE_WL_0_1(WL(1,0,1,0),4,COEFS,4,4,WL(1,0,1,7))
      CALL FFV1L2_1(PL(0,7),W(2),GC_5,ZERO,ZERO,PL(0,8),COEFS)
      CALL ML5_0_UPDATE_WL_1_1(WL(1,0,1,7),4,COEFS,4,4,WL(1,0,1,8))
      CALL FFV1L2_1(PL(0,8),W(4),GC_5,ZERO,ZERO,PL(0,9),COEFS)
      CALL ML5_0_UPDATE_WL_2_1(WL(1,0,1,8),4,COEFS,4,4,WL(1,0,1,9))
      CALL FFV1L2_1(PL(0,9),W(3),GC_5,ZERO,ZERO,PL(0,10),COEFS)
      CALL ML5_0_UPDATE_WL_3_1(WL(1,0,1,9),4,COEFS,4,4,WL(1,0,1,10))
      CALL ML5_0_CREATE_LOOP_COEFS(WL(1,0,1,10),4,4,3,1,1,41)
C     Coefficient construction for loop diagram with ID 4
      CALL FFV1L1_2(PL(0,1),W(3),GC_5,ZERO,ZERO,PL(0,11),COEFS)
      CALL ML5_0_UPDATE_WL_1_1(WL(1,0,1,1),4,COEFS,4,4,WL(1,0,1,11))
      CALL FFV1L1_2(PL(0,11),W(2),GC_5,ZERO,ZERO,PL(0,12),COEFS)
      CALL ML5_0_UPDATE_WL_2_1(WL(1,0,1,11),4,COEFS,4,4,WL(1,0,1,12))
      CALL FFV1L1_2(PL(0,12),W(4),GC_5,ZERO,ZERO,PL(0,13),COEFS)
      CALL ML5_0_UPDATE_WL_3_1(WL(1,0,1,12),4,COEFS,4,4,WL(1,0,1,13))
      CALL ML5_0_CREATE_LOOP_COEFS(WL(1,0,1,13),4,4,4,1,1,42)
C     Coefficient construction for loop diagram with ID 5
      CALL FFV1L2_1(PL(0,8),W(3),GC_5,ZERO,ZERO,PL(0,14),COEFS)
      CALL ML5_0_UPDATE_WL_2_1(WL(1,0,1,8),4,COEFS,4,4,WL(1,0,1,14))
      CALL FFV1L2_1(PL(0,14),W(4),GC_5,ZERO,ZERO,PL(0,15),COEFS)
      CALL ML5_0_UPDATE_WL_3_1(WL(1,0,1,14),4,COEFS,4,4,WL(1,0,1,15))
      CALL ML5_0_CREATE_LOOP_COEFS(WL(1,0,1,15),4,4,5,1,1,43)
C     Coefficient construction for loop diagram with ID 6
      CALL FFV1L2_1(PL(0,7),W(3),GC_5,ZERO,ZERO,PL(0,16),COEFS)
      CALL ML5_0_UPDATE_WL_1_1(WL(1,0,1,7),4,COEFS,4,4,WL(1,0,1,16))
      CALL FFV1L2_1(PL(0,16),W(2),GC_5,ZERO,ZERO,PL(0,17),COEFS)
      CALL ML5_0_UPDATE_WL_2_1(WL(1,0,1,16),4,COEFS,4,4,WL(1,0,1,17))
      CALL FFV1L2_1(PL(0,17),W(4),GC_5,ZERO,ZERO,PL(0,18),COEFS)
      CALL ML5_0_UPDATE_WL_3_1(WL(1,0,1,17),4,COEFS,4,4,WL(1,0,1,18))
      CALL ML5_0_CREATE_LOOP_COEFS(WL(1,0,1,18),4,4,6,1,1,44)
C     At this point, all loop coefficients needed for (QCD=8), i.e. of
C      split order ID=1, are computed.
      IF(FILTER_SO.AND.SQSO_TARGET.EQ.1) GOTO 4000

      GOTO 1001
 4000 CONTINUE
      LOOP_REQ_SO_DONE=.TRUE.
 1001 CONTINUE
      END

      SUBROUTINE ML5_0_AUDIT_ASSEMBLE()
C     
C     Modules
C     
      USE ML5_0_POLYNOMIAL_CONSTANTS
      USE ALOHA_OBJECT
C     
      IMPLICIT NONE
C     
C     CONSTANTS
C     
      INTEGER    NEXTERNAL
      PARAMETER (NEXTERNAL=4)
      INTEGER    NCOMB
      PARAMETER (NCOMB=16)
      INTEGER    NLOOPS, NLOOPGROUPS, NCTAMPS
      PARAMETER (NLOOPS=6, NLOOPGROUPS=6, NCTAMPS=38)
      INTEGER    NLOOPAMPS
      PARAMETER (NLOOPAMPS=44)
      INTEGER    NWAVEFUNCS,NLOOPWAVEFUNCS
      PARAMETER (NWAVEFUNCS=4,NLOOPWAVEFUNCS=18)
      REAL*8     ZERO
      PARAMETER (ZERO=0D0)
      REAL*16     MP__ZERO
      PARAMETER (MP__ZERO=0.0E0_16)
C     These are constants related to the split orders
      INTEGER    NSO, NSQUAREDSO, NAMPSO
      PARAMETER (NSO=1, NSQUAREDSO=1, NAMPSO=1)
C     
C     ARGUMENTS
C     
      REAL*8 P(0:3,NEXTERNAL)
      INTEGER NHEL(NEXTERNAL), IC(NEXTERNAL)
      INTEGER H
C     
C     LOCAL VARIABLES
C     
      INTEGER I,J,K
      INTEGER FLAVOR(NEXTERNAL)
      DATA FLAVOR /NEXTERNAL*1/
      COMPLEX*16 COEFS(MAXLWFSIZE,0:VERTEXMAXCOEFS-1,MAXLWFSIZE)

      LOGICAL DUMMYFALSE
      DATA DUMMYFALSE/.FALSE./
C     
C     GLOBAL VARIABLES
C     

      INCLUDE 'coupl.inc'
      INCLUDE 'mp_coupl.inc'

      INTEGER HELOFFSET
      INTEGER GOODHEL(NCOMB)
      LOGICAL GOODAMP(NSQUAREDSO,NLOOPGROUPS)
      COMMON/ML5_0_FILTERS/GOODAMP,GOODHEL,HELOFFSET

      LOGICAL CHECKPHASE
      LOGICAL HELDOUBLECHECKED
      COMMON/ML5_0_INIT/CHECKPHASE, HELDOUBLECHECKED

      INTEGER SQSO_TARGET
      COMMON/ML5_0_SOCHOICE/SQSO_TARGET

      LOGICAL UVCT_REQ_SO_DONE,MP_UVCT_REQ_SO_DONE,CT_REQ_SO_DONE
     $ ,MP_CT_REQ_SO_DONE,LOOP_REQ_SO_DONE,MP_LOOP_REQ_SO_DONE
     $ ,CTCALL_REQ_SO_DONE,FILTER_SO
      COMMON/ML5_0_SO_REQS/UVCT_REQ_SO_DONE,MP_UVCT_REQ_SO_DONE
     $ ,CT_REQ_SO_DONE,MP_CT_REQ_SO_DONE,LOOP_REQ_SO_DONE
     $ ,MP_LOOP_REQ_SO_DONE,CTCALL_REQ_SO_DONE,FILTER_SO

      INTEGER I_SO
      COMMON/ML5_0_I_SO/I_SO
      INTEGER I_LIB
      COMMON/ML5_0_I_LIB/I_LIB

      TYPE(ALOHA) W(NWAVEFUNCS)
      COMMON/ML5_0_W/W
      COMPLEX*16 WL(MAXLWFSIZE,0:LOOPMAXCOEFS-1,MAXLWFSIZE,
     $ -1:NLOOPWAVEFUNCS)
      COMPLEX*16 PL(0:3,-1:NLOOPWAVEFUNCS)
      COMMON/ML5_0_WL/WL,PL

      COMPLEX*16 AMPL(3,NLOOPAMPS)
      COMMON/ML5_0_AMPL/AMPL

C     
      COMPLEX*16 LOOPCOEFS(0:LOOPMAXCOEFS-1,NLOOPGROUPS)
      COMMON/ML5_0_LCOEFS/LOOPCOEFS
C     Replay one exact generated diagram with external wavefunctions fixed.
      LOOPCOEFS(:,2)=(0D0,0D0)
      CALL FFV1L1_2(PL(0,0),W(1),GC_5,ZERO,ZERO,PL(0,1),COEFS)
      CALL ML5_0_UPDATE_WL_0_1(WL(1,0,1,0),4,COEFS,4,4,WL(1,0,1,1))
      CALL FFV1L1_2(PL(0,1),W(2),GC_5,ZERO,ZERO,PL(0,2),COEFS)
      CALL ML5_0_UPDATE_WL_1_1(WL(1,0,1,1),4,COEFS,4,4,WL(1,0,1,2))
      CALL FFV1L1_2(PL(0,2),W(3),GC_5,ZERO,ZERO,PL(0,5),COEFS)
      CALL ML5_0_UPDATE_WL_2_1(WL(1,0,1,2),4,COEFS,4,4,WL(1,0,1,5))
      CALL FFV1L1_2(PL(0,5),W(4),GC_5,ZERO,ZERO,PL(0,6),COEFS)
      CALL ML5_0_UPDATE_WL_3_1(WL(1,0,1,5),4,COEFS,4,4,WL(1,0,1,6))
      CALL ML5_0_CREATE_LOOP_COEFS(WL(1,0,1,6),4,4,2,1,1,40)
      END
