      SUBROUTINE ML5_0_TIRLOOP(I_SQSO,I_LOOPGROUP,I_LIB,NLOOPLINE,PL
     $ ,M2L,RANK,RES,STABLE)
C     
C     Generated by MadGraph7 v. 0.2.1, 2026-09-24
C     By the MadGraph7 Development Team
C     Visit launchpad.net/madgraph5 and amcatnlo.web.cern.ch
C     
C     Interface between MG5 and TIR.
C     
C     Process: g g > h h [ sqrvirt = QCD ]
C     
C     
C     CONSTANTS 
C     
      INTEGER NLOOPGROUPS
      PARAMETER (NLOOPGROUPS=6)
C     These are constants related to the split orders
      INTEGER NSQUAREDSO
      PARAMETER (NSQUAREDSO=1)
      INCLUDE 'loop_max_coefs.inc'
      INTEGER    NEXTERNAL
      PARAMETER (NEXTERNAL=4)
      LOGICAL CHECKPCONSERVATION
      PARAMETER (CHECKPCONSERVATION=.TRUE.)
      REAL*8 NORMALIZATION
      PARAMETER (NORMALIZATION = 1.D0/(16.D0*3.14159265358979323846D0*
     $ *2))
      INTEGER TIR_CACHE_SIZE
      INCLUDE 'tir_cache_size.inc'
C     
C     ARGUMENTS 
C     
      INTEGER I_SQSO,I_LOOPGROUP,I_LIB
      INTEGER NLOOPLINE, RANK
      REAL*8 PL(0:3,NLOOPLINE)
      REAL*8 PCT(0:3,0:NLOOPLINE-1),ABSPCT(0:3)
      REAL*8 REF_P
      REAL*8 PDEN(0:3,NLOOPLINE-1)
      COMPLEX*16 M2L(NLOOPLINE)
      COMPLEX*16 M2LCT(0:NLOOPLINE-1)
      COMPLEX*16 RES(3)
      LOGICAL STABLE
C     
C     LOCAL VARIABLES 
C     
      INTEGER I, J, K
      INTEGER NLOOPCOEFS
      COMPLEX*16 AUDIT_Q(0:3),AUDIT_VALUE
      LOGICAL CTINIT, TIRINIT, GOLEMINIT, SAMURAIINIT, NINJAINIT
     $ ,COLLIERINIT
      COMMON/REDUCTIONCODEINIT/CTINIT,TIRINIT,GOLEMINIT,SAMURAIINIT
     $ ,NINJAINIT,COLLIERINIT

C     This variable will be used to detect changes in the TIR library
C      used so as to force the reset of the TIR filter.
      INTEGER LAST_LIB_USED
      DATA LAST_LIB_USED/-1/

      COMPLEX*16 TIRCOEFS(0:LOOPMAXCOEFS-1,3)
     $ ,TIRCOEFSERRORS(0:LOOPMAXCOEFS-1,3)
      COMPLEX*16 PJCOEFS(0:LOOPMAXCOEFS-1,3)
      INTEGER TIR_CACHE_INDEX
      COMPLEX*16 TIRCOEFS_CACHING(3,0:LOOPMAXCOEFS-1,NLOOPGROUPS
     $ ,TIR_CACHE_SIZE)
      SAVE TIRCOEFS_CACHING
C     
C     EXTERNAL FUNCTIONS
C     
      INTEGER ML5_0_TIRCACHE_INDEX
C     
C     GLOBAL VARIABLES
C     
      INCLUDE 'MadLoopParams.inc'

      INCLUDE 'coupl.inc'
      INTEGER CTMODE
      REAL*8 LSCALE
      COMMON/ML5_0_CT/LSCALE,CTMODE

      INTEGER ID,R
      COMMON/ML5_0_LOOP/ID,R

C     The argument ILIB is the TIR library to be used for that
C      specific library.
      INTEGER LIBINDEX
      COMMON/ML5_0_I_LIB/LIBINDEX

      COMPLEX*16 LOOPCOEFS(0:LOOPMAXCOEFS-1,NLOOPGROUPS)
      COMMON/ML5_0_LCOEFS/LOOPCOEFS
C     The index 0 of the second dimensions is filled with .false. as
C      it makes the implementation simpler this way when the user sets
C      TIR_CACHE_SIZE to be 0.
      LOGICAL TIR_DONE(NLOOPGROUPS,0:TIR_CACHE_SIZE)
      COMMON/ML5_0_TIRCACHING/TIR_DONE
C     ----------
C     BEGIN CODE
C     ----------

C     Initialize for the very first time ML is called LAST_ILIB with
C      the first ILIB used.
      IF(LAST_LIB_USED.EQ.-1) THEN
        LAST_LIB_USED = MLREDUCTIONLIB(LIBINDEX)
      ELSE
C       We changed the TIR library so we must refresh the cache.
        IF(MLREDUCTIONLIB(LIBINDEX).NE.LAST_LIB_USED) THEN
          LAST_LIB_USED = MLREDUCTIONLIB(LIBINDEX)
          CALL ML5_0_CLEAR_TIR_CACHE()
        ENDIF
      ENDIF

      IF (MLREDUCTIONLIB(I_LIB).EQ.4) THEN
C       Golem95 not available
        WRITE(*,*) 'ERROR:: Golem95 is not interfaced.'
        STOP
      ENDIF

C     INITIALIZE TIR IF NEEDED
      IF (TIRINIT) THEN
        TIRINIT=.FALSE.
        CALL ML5_0_INITTIR()
      ENDIF

C     CONVERT THE MASSES TO BE COMPLEX
      DO I=1,NLOOPLINE
        M2LCT(I-1)=M2L(I)
      ENDDO

C     CONVERT THE MOMENTA FLOWING IN THE LOOP LINES TO CT CONVENTIONS
      DO I=0,3
        ABSPCT(I) = 0.D0
        DO J=0,(NLOOPLINE-1)
          PCT(I,J)=0.D0
        ENDDO
      ENDDO
      DO I=0,3
        DO J=1,NLOOPLINE
          PCT(I,0)=PCT(I,0)+PL(I,J)
          ABSPCT(I)=ABSPCT(I)+ABS(PL(I,J))
        ENDDO
      ENDDO
      REF_P = MAX(ABSPCT(0), ABSPCT(1),ABSPCT(2),ABSPCT(3))
      DO I=0,3
        ABSPCT(I) = MAX(REF_P*1E-6, ABSPCT(I))
      ENDDO

      IF (CHECKPCONSERVATION.AND.REF_P.GT.1D-8) THEN
        IF ((PCT(0,0)/ABSPCT(0)).GT.1.D-6) THEN
          WRITE(*,*) 'energy is not conserved (flag: TIR)',PCT(0,0)
          STOP 'energy is not conserved (flag: TIR)'
        ELSEIF ((PCT(1,0)/ABSPCT(1)).GT.1.D-6) THEN
          WRITE(*,*) 'px is not conserved (flag: TIR)',PCT(1,0)
          STOP 'px is not conserved (flag: TIR)'
        ELSEIF ((PCT(2,0)/ABSPCT(2)).GT.1.D-6) THEN
          WRITE(*,*) 'py is not conserved (flag: TIR)',PCT(2,0)
          STOP 'py is not conserved (flag: TIR)'
        ELSEIF ((PCT(3,0)/ABSPCT(3)).GT.1.D-6) THEN
          WRITE(*,*) 'pz is not conserved (flag: TIR)',PCT(3,0)
          STOP 'pz is not conserved (flag: TIR)'
        ENDIF
      ENDIF
      DO I=0,3
        DO J=1,(NLOOPLINE-1)
          DO K=1,J
            PCT(I,J)=PCT(I,J)+PL(I,K)
          ENDDO
        ENDDO
      ENDDO

      DO I=0,3
        DO J=1,(NLOOPLINE-1)
          PDEN(I,J)=PCT(I,J)
        ENDDO
      ENDDO
C     NUMBER OF INDEPEDENT LOOPCOEFS FOR RANK=RANK
      NLOOPCOEFS=0
      DO I=0,RANK
        NLOOPCOEFS=NLOOPCOEFS+(3+I)*(2+I)*(1+I)/6
      ENDDO
      IF (TIR_CACHE_SIZE.EQ.0) THEN
        TIR_CACHE_INDEX = 0
      ELSE
        TIR_CACHE_INDEX = ML5_0_TIRCACHE_INDEX(CTMODE)
C       This way whenever the CTMode exceeds the cache size it rolls
C        back to the beginning and MadLoop will have taken care of
C        having re-initialized TIR_DONE between labels 200 and 205 in
C        loop_matrix.f
        TIR_CACHE_INDEX = MOD(TIR_CACHE_INDEX-1,TIR_CACHE_SIZE)+1
      ENDIF

      IF(.NOT.TIR_DONE(I_LOOPGROUP,TIR_CACHE_INDEX))THEN
        SELECT CASE(MLREDUCTIONLIB(I_LIB))
        CASE(2)
C         PJFry++
          WRITE(*,*) 'ERROR:: PJFRY++ is not interfaced.'
          STOP
        CASE(3)
C         IREGI
          CALL ML5_0_AUDIT_CHECK_POLICY()
          CALL IMLOOP(CTMODE,IREGIMODE,NLOOPLINE,LOOPMAXCOEFS,RANK
     $     ,PDEN,M2L,MU_R,PJCOEFS,STABLE)
C         CONVERT TO MADLOOP CONVENTION
          CALL ML5_0_CONVERT_IREGI_COEFFS(RANK,PJCOEFS,TIRCOEFS)
        CASE(7)
C         COLLIER
          WRITE(*,*) 'ERROR:: COLLIER is not interfaced.'
          STOP
        END SELECT
C       The zero index is dummy and means no caching at all since
C        TIR_CACHE_SIZE=0.
        IF(TIR_CACHE_INDEX.NE.0) THEN
          DO I=1,3
            DO J=0,NLOOPCOEFS-1
              TIRCOEFS_CACHING(I,J,I_LOOPGROUP,TIR_CACHE_INDEX)
     $         =TIRCOEFS(J,I)
            ENDDO
          ENDDO
          TIR_DONE(I_LOOPGROUP,TIR_CACHE_INDEX)=.TRUE.
        ENDIF
      ELSE
        DO I=1,3
          DO J=0,NLOOPCOEFS-1
            TIRCOEFS(J,I)=TIRCOEFS_CACHING(I,J,I_LOOPGROUP
     $       ,TIR_CACHE_INDEX)
          ENDDO
        ENDDO
      ENDIF
      DO I=1,3
        RES(I)=(0.0D0,0.0D0)
        DO J=0,NLOOPCOEFS-1
          RES(I)=RES(I)+LOOPCOEFS(J,I_LOOPGROUP)*TIRCOEFS(J,I)
        ENDDO
      ENDDO
C     IREGI audit: individual bare loop, before normalization or CT sum.
      WRITE(*,*) 'IREGI_AUDIT_BEGIN',I_LOOPGROUP,NLOOPLINE,RANK,
     $ CTMODE,STABLE
      WRITE(*,'(A,ES26.17E3)') 'IREGI_SCALE ',MU_R
      WRITE(*,'(A,I4,4ES26.17E3)') 'IREGI_SHIFT ',0,0D0,0D0,0D0,0D0
      DO J=1,NLOOPLINE-1
        WRITE(*,'(A,I4,4ES26.17E3)') 'IREGI_SHIFT ',J,
     $    (PDEN(I,J),I=0,3)
      ENDDO
      DO J=0,NLOOPLINE-1
        WRITE(*,'(A,I4,2ES26.17E3)') 'IREGI_MASS ',J,
     $    DBLE(M2L(J+1)),DIMAG(M2L(J+1))
      ENDDO
      DO J=0,NLOOPCOEFS-1
        WRITE(*,'(A,I4,2ES26.17E3)') 'IREGI_NUM ',J,
     $    DBLE(LOOPCOEFS(J,I_LOOPGROUP)),
     $    DIMAG(LOOPCOEFS(J,I_LOOPGROUP))
        DO I=1,3
          WRITE(*,'(A,2I4,2ES26.17E3)') 'IREGI_TENSOR ',J,I,
     $      DBLE(TIRCOEFS(J,I)),DIMAG(TIRCOEFS(J,I))
        ENDDO
      ENDDO
      DO I=1,3
        WRITE(*,'(A,I4,4ES26.17E3)') 'IREGI_RESULT ',I,
     $    DBLE(RES(I)),DIMAG(RES(I)),
     $    DBLE(NORMALIZATION*RES(I)),DIMAG(NORMALIZATION*RES(I))
      ENDDO
C     Use MadLoop's own polynomial evaluator for the pointwise reference.
      AUDIT_Q(0)=DCMPLX(2.0D0,0.25D0)
      AUDIT_Q(1)=DCMPLX(-3.0D0,0.125D0)
      AUDIT_Q(2)=DCMPLX(5.0D0,-0.5D0)
      AUDIT_Q(3)=DCMPLX(7.0D0,0.75D0)
      CALL ML5_0_EVAL_POLY(LOOPCOEFS(0,I_LOOPGROUP),RANK,
     $ AUDIT_Q,AUDIT_VALUE)
      WRITE(*,'(A,2ES26.17E3)') 'IREGI_PROBE ',
     $ DBLE(AUDIT_VALUE),DIMAG(AUDIT_VALUE)
      CALL ML5_0_AUDIT_REPORT_POLICY(I_LOOPGROUP)
      WRITE(*,*) 'IREGI_AUDIT_END'
      IF(I_LOOPGROUP.EQ.2) CALL ML5_0_AUDIT_BENCH(
     $ NLOOPLINE,RANK,NLOOPCOEFS,PDEN,M2L,MU_R,CTMODE,IREGIMODE,
     $ TIRCOEFS,RES)
      RES(1)=NORMALIZATION*RES(1)
      RES(2)=NORMALIZATION*RES(2)
      RES(3)=NORMALIZATION*RES(3)
C     IF(MLReductionLib(I_LIB).EQ.2) THEN
C     WRITE(*,*) 'PJFry: Loop ID',ID,' =',RES(1),RES(2),RES(3)
C     ELSEIF(MLReductionLib(I_LIB).EQ.3) THEN
C     WRITE(*,*) 'Iregi: Loop ID',ID,' =',RES(1),RES(2),RES(3)
C     ELSEIF(MLReductionLib(I_LIB).EQ.7) THEN
C     WRITE(*,*) 'COLLIER: Loop ID',ID,' =',RES(1),RES(2),RES(3)
C     ENDIF
      END

      SUBROUTINE ML5_0_SWITCH_ORDER(CTMODE,NLOOPLINE,PL,PDEN,M2L)
      IMPLICIT NONE

      INTEGER CTMODE,NLOOPLINE

      REAL*8 PL(0:3,NLOOPLINE)
      REAL*8 PDEN(0:3,NLOOPLINE-1)
      COMPLEX*16 M2L(NLOOPLINE)
      REAL*8 NEW_PL(0:3,NLOOPLINE)
      REAL*8 NEW_PDEN(0:3,NLOOPLINE-1)
      COMPLEX*16 NEW_M2L(NLOOPLINE)

      INTEGER I,J,K

      IF (CTMODE.NE.2.AND.CTMODE.NE.5) THEN
        RETURN
      ENDIF

      IF (NLOOPLINE.LE.2) THEN
        RETURN
      ENDIF

      DO I=1,NLOOPLINE-1
        DO J=0,3
          NEW_PDEN(J,NLOOPLINE-I) = PDEN(J,I)
        ENDDO
      ENDDO
      DO I=1,NLOOPLINE-1
        DO J=0,3
          PDEN(J,I) = NEW_PDEN(J,I)
        ENDDO
      ENDDO

      DO I=2,NLOOPLINE
        NEW_M2L(I)=M2L(NLOOPLINE-I+2)
      ENDDO
      DO I=2,NLOOPLINE
        M2L(I)=NEW_M2L(I)
      ENDDO


      DO I=1,NLOOPLINE
        DO J=0,3
          NEW_PL(J,I) = -PL(J,NLOOPLINE+1-I)
        ENDDO
      ENDDO
      DO I=1,NLOOPLINE
        DO J=0,3
          PL(J,I) = NEW_PL(J,I)
        ENDDO
      ENDDO

      END

      SUBROUTINE ML5_0_MP_SWITCH_ORDER(CTMODE,NLOOPLINE,PL,PDEN,M2L)
      IMPLICIT NONE

      INTEGER CTMODE,NLOOPLINE

      REAL*16 PL(0:3,NLOOPLINE)
      REAL*16 PDEN(0:3,NLOOPLINE-1)
